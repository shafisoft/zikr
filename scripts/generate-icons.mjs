/**
 * Generates src/ui/components/icons/iconPaths.generated.ts — the inline-SVG
 * path data backing MaterialIcon.tsx.
 *
 * Why generated + committed: icons are baked into the JS bundle so the app
 * renders identically offline. (The previous Material Symbols icon font came
 * from Google Fonts as ~50 unicode-range slices; the slice carrying the
 * ligature data intermittently missed the SW cache, and icons degraded to raw
 * ligature text like "cloud_off" offline.)
 *
 * Usage: npm run gen:icons  (run after adding an icon name to ICONS below)
 *
 * The script also fail-closes on:
 *  - icon names used in src/ but missing from ICONS (add them here)
 *  - any reintroduction of the .material-symbols-outlined font class
 */
